enum TicketType {
	UNKNOWN = -1,
ORDINARY, 
NAMED, 
SPECIAL
};
class Ticket {
public:
	Ticket(int date, int hour, int numberOfRooms, double price, TicketType type) {
		this->date = date;
		this->hour = hour;
		while (numberOfRooms > 10) {
			std::cout << "Invalid number!";
			std::cin >> numberOfRooms;
		}
		this->numberOfRoom = numberOfRooms;
		this->price = price;
		this->type = type;
	} 
	Ticket() {
		date = 0;
		hour = 0;
		numberOfRoom = 0;
		price = 0.0;
		type = UNKNOWN;
	}
	double calculatePrice() {
		if (type == ORDINARY) {
			return price;
		}
		else if (type == NAMED) {
			price *= 3;
			return price;
		}
		else if (type == SPECIAL) {
			price = 0;
			return price;
		}
	}
private:
	int date;
	int hour;
	int numberOfRoom;
	double price;
	TicketType type;
};

class OrdinaryTicket: public Ticket {
public:
	OrdinaryTicket(int row, int seat) {
		while (row > 100 || seat > 100) {
			std::cout << "Invalid row or seat!";
			std::cin >> row;
			std::cin >> seat;
		}
		this->row = row;
		this->seat = seat;
	}
	OrdinaryTicket() {
		row = 0;
		seat = 0;
	}
private:
	int row;
	int seat;
};

class NamedTicket : public Ticket {
public:
	NamedTicket(std::string name, int Lnumber) {
		this->name = name;
		while (Lnumber > 100) {
			std::cout << "Invalid number!";
			std::cin >> Lnumber;
		}
		this->Lnumber = Lnumber;
	} NamedTicket() {
		name = "";
		Lnumber = 0;
	}
private:
	std::string name;
	int Lnumber;
};

class SpecialTicket : public Ticket {
public:
	SpecialTicket(std::string name, int Lnumber, int actorsD, int actorsH) {
		this->name = name;

		this->Lnumber = Lnumber;
		this->actorsDate = actorsD;
		this->actorsHour = actorsH;
	} 
	SpecialTicket() {
		name = "";
		Lnumber = 0;
		actorsDate = 0;
		actorsHour = 0;
	}
private:
	std::string name;
	int Lnumber;
	int actorsDate;
	int actorsHour;
};

double getPrice(Ticket* tickets, int ticketSize) {
	double price = 0;
	for (int i = 0; i < ticketSize; ++i) {
		price += tickets[i].calculatePrice();
	}
	return price;
}
